"""Package the ST-MambaIR training and evaluation code."""

import subprocess
from pathlib import Path

from setuptools import find_packages, setup

ROOT = Path(__file__).resolve().parent


def write_version_py():
    version = (ROOT / 'VERSION').read_text(encoding='utf-8').strip()
    try:
        sha = subprocess.check_output(
            ['git', 'rev-parse', '--short', 'HEAD'], cwd=ROOT,
            stderr=subprocess.DEVNULL).decode().strip()
    except (OSError, subprocess.CalledProcessError):
        sha = 'unknown'
    version_info = tuple(int(part) if part.isdigit() else part for part in version.split('.'))
    (ROOT / 'basicsr' / 'version.py').write_text(
        '# Generated by setup.py.\n'
        f'__version__ = {version!r}\n'
        f'__gitsha__ = {sha!r}\n'
        f'version_info = {version_info!r}\n', encoding='utf-8')
    return version


if __name__ == '__main__':
    setup(
        name='st-mambair',
        version=write_version_py(),
        description='SuperToken state space modeling for thermal infrared image restoration',
        long_description=(ROOT / 'README.md').read_text(encoding='utf-8'),
        long_description_content_type='text/markdown',
        author='Dongming Wang',
        author_email='wangdongming@whut.edu.cn',
        url='https://github.com/wang2025-source/ST-MambaIR',
        packages=find_packages(include=('basicsr', 'basicsr.*')),
        include_package_data=True,
        license='Apache-2.0',
        python_requires='>=3.10',
        install_requires=[
            line.strip() for line in (ROOT / 'requirements.txt').read_text(encoding='utf-8').splitlines()
            if line.strip() and not line.lstrip().startswith('#')
        ],
        zip_safe=False,
    )
